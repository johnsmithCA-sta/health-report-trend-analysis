# ============ 参考范围解析工具 ============
def parse_reference(ref_str):
    """解析参考范围字符串 → {"lo": float|None, "hi": float|None, "qualitative": bool}"""
    if not ref_str:
        return {"lo": None, "hi": None, "qualitative": False}
    s = ref_str.strip()
    # 先匹配范围 "3.50-9.50"
    m = re.match(r'^([\d.]+)\s*-\s*([\d.]+)$', s)
    if m:
        return {"lo": float(m.group(1)), "hi": float(m.group(2)), "qualitative": False}
    # 单值
    m = re.match(r'^[-+]?[\d.]+$', s)
    if m:
        v = float(s)
        return {"lo": v, "hi": v, "qualitative": False}
    # 阈值 "<1" 或 ">5"
    m = re.match(r'^([<>])\s*([\d.]+)$', s)
    if m:
        v = float(m.group(2))
        if m.group(1) == "<":
            return {"lo": None, "hi": v, "qualitative": False}
        return {"lo": v, "hi": None, "qualitative": False}
    # 定性（阴性/阳性等）
    return {"lo": None, "hi": None, "qualitative": True}

def parse_numeric(value):
    """尝试将字符串值转为 float，失败返回 None"""
    try:
        return float(value)
    except (ValueError, TypeError):
        return None

def is_qualitative_value(value):
    """判断值是否为定性（文字性）结果"""
    if value is None:
        return True
    if isinstance(value, (int, float)):
        return False
    return not bool(re.match(r'^[-+]?\d*\.?\d+$', str(value).strip()))
